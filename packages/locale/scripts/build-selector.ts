/**
 * Bundles the country & language selector (src/selector.client.tsx: React +
 * @asafarim/country-language-selector) into selector.js and copies its styles into selector.css, the two
 * files every page loads from its own origin:
 *
 *   pnpm --filter @asafarim/locale build:selector
 *
 * To upgrade the selector everywhere: bump @asafarim/country-language-selector in this package, run this,
 * commit. test/selector.test.ts fails while the committed files differ from a fresh build, and every image
 * copies them from here.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT = path.join(here, "selector.js");
export const STYLES = path.join(here, "selector.css");
const require = createRequire(import.meta.url);

const versionOf = (name: string) =>
  (JSON.parse(readFileSync(require.resolve(`${name}/package.json`), "utf8")) as { version: string }).version;

/** `{ js, css }` as they should be committed. */
export async function render(): Promise<{ js: string; css: string }> {
  const esbuild = await import("esbuild");
  const result = await esbuild.build({
    entryPoints: [path.join(here, "src", "selector.client.tsx")],
    bundle: true,
    minify: true,
    format: "iife",
    target: "es2020",
    jsx: "automatic",
    define: { "process.env.NODE_ENV": '"production"' },
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const selector = `@asafarim/country-language-selector ${versionOf("@asafarim/country-language-selector")}`;
  const js = `/* @asafarim/locale selector: ${selector} + React ${versionOf("react")} (MIT). Generated by scripts/build-selector.ts; do not edit. */\n${result.outputFiles[0]?.text ?? ""}`;
  const css = `/* @asafarim/locale selector: ${selector} styles (MIT). Generated by scripts/build-selector.ts; do not edit. */\n${readFileSync(
    require.resolve("@asafarim/country-language-selector/styles.css"),
    "utf8",
  )}\n${readFileSync(path.join(here, "src", "selector-pill.css"), "utf8")}\n${readFileSync(path.join(here, "src", "links.css"), "utf8")}`;
  return { js, css };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { js, css } = await render();
  writeFileSync(OUTPUT, js);
  writeFileSync(STYLES, css);
  console.log(`locale: wrote selector.js (${Math.round(js.length / 1024)} KiB) and selector.css`);
}
